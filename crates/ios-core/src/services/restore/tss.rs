//! Peripheral TSS batch signing from device-generated preflight requests.

use std::collections::HashMap;
use std::io::Write;
use std::time::Duration;

use super::RestoreError;
use crate::xpc::XpcValue;

const TSS_URL: &str = "https://gs.apple.com/TSS/controller?action=2";
const MAX_TSS_RESPONSE: usize = 16 * 1024 * 1024;
const MAX_TSS_REQUEST: usize = 4 * 1024 * 1024;

/// One updater's complete signing request and expected ticket.
#[derive(Clone)]
pub struct TssRider {
    pub updater: String,
    pub ticket_key: String,
    pub nonce: Vec<u8>,
    pub request: plist::Dictionary,
}

/// A ticket held only while the corresponding runtime nonce still matches.
#[derive(Clone)]
pub struct PrefetchedTicket {
    pub updater: String,
    pub ticket_key: String,
    pub nonce: Vec<u8>,
    pub ticket: Vec<u8>,
}

impl PrefetchedTicket {
    /// Return the ticket for an exact runtime nonce match.
    pub fn for_nonce(&self, runtime_nonce: &[u8]) -> Option<&[u8]> {
        (self.nonce == runtime_nonce).then_some(self.ticket.as_slice())
    }
}

/// Result of a batch signing attempt and per-updater fallback.
#[derive(Default)]
pub struct TssBatchResult {
    pub tickets: HashMap<String, PrefetchedTicket>,
    pub failed_updaters: Vec<String>,
}

/// Extract an updater's device-built signing request and response ticket from a
/// `getdevicesidepreflightinfo` result. The caller provides the nonce observed
/// before the restore; runtime use must compare it to the live nonce.
pub fn rider_from_device_preflight(
    preflight: &indexmap::IndexMap<String, XpcValue>,
    updater: &str,
    nonce: &[u8],
) -> Result<TssRider, RestoreError> {
    let request = preflight
        .get("DeviceInfoRequests")
        .and_then(XpcValue::as_dict)
        .and_then(|requests| requests.get(updater))
        .ok_or_else(|| RestoreError::Protocol(format!("preflight missing {updater} request")))?;
    let tags = preflight
        .get("DeviceInfoTags")
        .and_then(XpcValue::as_dict)
        .and_then(|tags| tags.get(updater))
        .and_then(XpcValue::as_dict)
        .ok_or_else(|| RestoreError::Protocol(format!("preflight missing {updater} tags")))?;
    let ticket_key = match tags.get("ResponseTags") {
        Some(XpcValue::Array(keys)) if keys.len() == 1 => keys[0]
            .as_str()
            .filter(|key| key.ends_with(",Ticket"))
            .ok_or_else(|| RestoreError::Protocol("preflight response ticket invalid".into()))?,
        _ => {
            return Err(RestoreError::Protocol(
                "preflight requires one response ticket".into(),
            ))
        }
    };
    let request = xpc_to_plist(request, 0)?.into_dictionary().ok_or_else(|| {
        RestoreError::Protocol("preflight TSS request is not a dictionary".into())
    })?;
    let rider = TssRider {
        updater: updater.into(),
        ticket_key: ticket_key.into(),
        nonce: nonce.to_vec(),
        request,
    };
    validate_rider(&rider)?;
    Ok(rider)
}

fn xpc_to_plist(value: &XpcValue, depth: usize) -> Result<plist::Value, RestoreError> {
    if depth > 64 {
        return Err(RestoreError::Protocol(
            "preflight TSS request nesting exceeds 64".into(),
        ));
    }
    Ok(match value {
        XpcValue::Bool(value) => plist::Value::Boolean(*value),
        XpcValue::Int64(value) => plist::Value::Integer((*value).into()),
        XpcValue::Uint64(value) => plist::Value::Integer((*value).into()),
        XpcValue::Double(value) => plist::Value::Real(*value),
        XpcValue::Data(value) => plist::Value::Data(value.to_vec()),
        XpcValue::String(value) => plist::Value::String(value.clone()),
        XpcValue::Array(values) => plist::Value::Array(
            values
                .iter()
                .map(|value| xpc_to_plist(value, depth + 1))
                .collect::<Result<_, _>>()?,
        ),
        XpcValue::Dictionary(values) => plist::Value::Dictionary(
            values
                .iter()
                .map(|(key, value)| Ok((key.clone(), xpc_to_plist(value, depth + 1)?)))
                .collect::<Result<_, RestoreError>>()?,
        ),
        _ => {
            return Err(RestoreError::Protocol(
                "unsupported preflight TSS field".into(),
            ))
        }
    })
}

/// Merge peripheral signing requests into one POST without mixing in AP ticket flags.
/// Distinct values for the same key are rejected; the caller can sign those riders
/// individually. A caller must supply chip-specific requests generated by the device
/// or verified against them; this function does not guess peripheral TSS fields.
pub fn build_tss_batch_request(riders: &[TssRider]) -> Result<plist::Dictionary, RestoreError> {
    if riders.is_empty() {
        return Err(RestoreError::Protocol("TSS batch has no riders".into()));
    }
    let mut merged = plist::Dictionary::new();
    merged.insert(
        "@UUID".into(),
        plist::Value::String(uuid::Uuid::new_v4().to_string().to_uppercase()),
    );
    for rider in riders {
        validate_rider(rider)?;
        for (key, value) in &rider.request {
            if key == "@UUID" {
                continue;
            }
            if key == "@ApImg4Ticket" && value == &plist::Value::Boolean(true) {
                return Err(RestoreError::Protocol(
                    "peripheral batch cannot request an AP ticket".into(),
                ));
            }
            if let Some(existing) = merged.get(key) {
                if existing != value {
                    return Err(RestoreError::Protocol(format!(
                        "TSS batch has conflicting {key} fields"
                    )));
                }
            } else {
                merged.insert(key.clone(), value.clone());
            }
        }
    }
    Ok(merged)
}

fn validate_rider(rider: &TssRider) -> Result<(), RestoreError> {
    if rider.updater.is_empty()
        || rider.ticket_key.is_empty()
        || rider.nonce.is_empty()
        || rider.nonce.len() > 64
        || rider.request.get(&format!("@{}", rider.ticket_key))
            != Some(&plist::Value::Boolean(true))
        || rider.request.get("@ApImg4Ticket") == Some(&plist::Value::Boolean(true))
    {
        return Err(RestoreError::Protocol(
            "invalid peripheral TSS rider".into(),
        ));
    }
    Ok(())
}

/// Sign all riders in one POST and retry individually if the combined request fails.
/// The signer callback permits an offline fake TSS service. Missing tickets remain
/// failures for the reactive signing path instead of being treated as success.
pub async fn prefetch_tss_batch<F, Fut>(
    riders: &[TssRider],
    mut signer: F,
) -> Result<TssBatchResult, RestoreError>
where
    F: FnMut(plist::Dictionary) -> Fut,
    Fut: std::future::Future<Output = Result<plist::Dictionary, RestoreError>>,
{
    let mut result = TssBatchResult::default();
    if riders.is_empty() {
        return Ok(result);
    }
    for rider in riders {
        validate_rider(rider)?;
    }
    let combined = build_tss_batch_request(riders);
    if let Ok(request) = combined {
        if let Ok(response) = signer(request).await {
            for rider in riders {
                if !store_ticket(&mut result, rider, &response) {
                    match signer(rider.request.clone()).await {
                        Ok(individual) if store_ticket(&mut result, rider, &individual) => {}
                        _ => result.failed_updaters.push(rider.updater.clone()),
                    }
                }
            }
            return Ok(result);
        }
    }
    for rider in riders {
        validate_rider(rider)?;
        match signer(rider.request.clone()).await {
            Ok(response) if store_ticket(&mut result, rider, &response) => {}
            _ => result.failed_updaters.push(rider.updater.clone()),
        }
    }
    Ok(result)
}

fn store_ticket(
    result: &mut TssBatchResult,
    rider: &TssRider,
    response: &plist::Dictionary,
) -> bool {
    if let Some(ticket) = response
        .get(&rider.ticket_key)
        .and_then(plist::Value::as_data)
        .filter(|ticket| !ticket.is_empty())
    {
        result.tickets.insert(
            rider.updater.clone(),
            PrefetchedTicket {
                updater: rider.updater.clone(),
                ticket_key: rider.ticket_key.clone(),
                nonce: rider.nonce.clone(),
                ticket: ticket.to_vec(),
            },
        );
        true
    } else {
        false
    }
}

/// POST one signing request to Apple's TSS with bounded time and response size.
pub async fn sign_tss_request(
    request: &plist::Dictionary,
) -> Result<plist::Dictionary, RestoreError> {
    let client = reqwest::Client::builder()
        .connect_timeout(Duration::from_secs(30))
        .timeout(Duration::from_secs(120))
        .build()
        .map_err(|error| RestoreError::Protocol(format!("TSS client setup failed: {error}")))?;
    sign_tss_request_with_client(&client, TSS_URL, request).await
}

/// Sign against a specified endpoint, useful for local protocol simulation.
pub async fn sign_tss_request_with_client(
    client: &reqwest::Client,
    url: &str,
    request: &plist::Dictionary,
) -> Result<plist::Dictionary, RestoreError> {
    let mut body = LimitedWriter::new(MAX_TSS_REQUEST);
    let encoded = plist::to_writer_xml(&mut body, request);
    if body.overflowed {
        return Err(RestoreError::Protocol("TSS request exceeds 4 MiB".into()));
    }
    encoded
        .map_err(|error| RestoreError::Protocol(format!("TSS request encode failed: {error}")))?;
    let mut response = client
        .post(url)
        .header("Content-Type", "text/xml; charset=\"utf-8\"")
        .header("User-Agent", "InetURL/1.0")
        .body(body.bytes)
        .send()
        .await
        .map_err(|error| RestoreError::Protocol(format!("TSS HTTP request failed: {error}")))?;
    if !response.status().is_success() {
        return Err(RestoreError::Protocol(format!(
            "TSS returned HTTP {}",
            response.status()
        )));
    }
    let mut body = Vec::new();
    while let Some(chunk) = response
        .chunk()
        .await
        .map_err(|error| RestoreError::Protocol(format!("TSS response read failed: {error}")))?
    {
        if chunk.len() > MAX_TSS_RESPONSE - body.len() {
            return Err(RestoreError::Protocol("TSS response exceeds 16 MiB".into()));
        }
        body.extend_from_slice(&chunk);
    }
    parse_tss_response(&body)
}

struct LimitedWriter {
    bytes: Vec<u8>,
    limit: usize,
    overflowed: bool,
}

impl LimitedWriter {
    fn new(limit: usize) -> Self {
        Self {
            bytes: Vec::new(),
            limit,
            overflowed: false,
        }
    }
}

impl Write for LimitedWriter {
    fn write(&mut self, buf: &[u8]) -> std::io::Result<usize> {
        if buf.len() > self.limit - self.bytes.len() {
            self.overflowed = true;
            return Err(std::io::Error::other("TSS request size limit"));
        }
        self.bytes.extend_from_slice(buf);
        Ok(buf.len())
    }

    fn flush(&mut self) -> std::io::Result<()> {
        Ok(())
    }
}

fn parse_tss_response(body: &[u8]) -> Result<plist::Dictionary, RestoreError> {
    let body = std::str::from_utf8(body)
        .map_err(|_| RestoreError::Protocol("TSS response is not UTF-8".into()))?;
    let status = body
        .split('&')
        .find_map(|field| field.strip_prefix("STATUS="));
    if status != Some("0") {
        return Err(RestoreError::Protocol("TSS did not return STATUS=0".into()));
    }
    let start = body
        .find("<?xml")
        .or_else(|| body.find("<plist"))
        .ok_or_else(|| RestoreError::Protocol("TSS response has no plist".into()))?;
    let value: plist::Value = plist::from_bytes(&body.as_bytes()[start..])
        .map_err(|error| RestoreError::Protocol(format!("TSS response plist invalid: {error}")))?;
    value
        .into_dictionary()
        .ok_or_else(|| RestoreError::Protocol("TSS response is not a dictionary".into()))
}

#[cfg(test)]
mod tests {
    use std::sync::atomic::{AtomicUsize, Ordering};
    use std::sync::Arc;

    use super::*;
    use indexmap::IndexMap;
    use tokio::io::{AsyncReadExt, AsyncWriteExt};

    fn rider(updater: &str, ticket_key: &str) -> TssRider {
        TssRider {
            updater: updater.into(),
            ticket_key: ticket_key.into(),
            nonce: vec![1, 2, 3],
            request: plist::Dictionary::from_iter([
                ("ApECID".into(), plist::Value::Integer(42.into())),
                (format!("@{ticket_key}"), plist::Value::Boolean(true)),
            ]),
        }
    }

    #[test]
    fn batch_keeps_peripheral_flags_and_rejects_ap_mix() {
        let mut rose = rider("Rose", "Rap,Ticket");
        rose.request
            .insert("@UUID".into(), plist::Value::String("rose-id".into()));
        let mut se = rider("SE", "SE2,Ticket");
        se.request
            .insert("@UUID".into(), plist::Value::String("se-id".into()));
        let request = build_tss_batch_request(&[rose, se]).unwrap();
        assert_eq!(request["@Rap,Ticket"], plist::Value::Boolean(true));
        assert_eq!(request["@SE2,Ticket"], plist::Value::Boolean(true));
        assert!(!request.contains_key("@ApImg4Ticket"));
        assert_ne!(request["@UUID"], plist::Value::String("rose-id".into()));
        let mut bad = rider("Rose", "Rap,Ticket");
        bad.request
            .insert("@ApImg4Ticket".into(), plist::Value::Boolean(true));
        assert!(build_tss_batch_request(&[bad]).is_err());
    }

    #[test]
    fn extracts_device_generated_rider_without_guessing_chip_fields() {
        let preflight = IndexMap::from([
            (
                "DeviceInfoRequests".into(),
                XpcValue::Dictionary(IndexMap::from([(
                    "Rose".into(),
                    XpcValue::Dictionary(IndexMap::from([
                        ("@Rap,Ticket".into(), XpcValue::Bool(true)),
                        ("Rap,ChipID".into(), XpcValue::Int64(8228)),
                    ])),
                )])),
            ),
            (
                "DeviceInfoTags".into(),
                XpcValue::Dictionary(IndexMap::from([(
                    "Rose".into(),
                    XpcValue::Dictionary(IndexMap::from([(
                        "ResponseTags".into(),
                        XpcValue::Array(vec![XpcValue::String("Rap,Ticket".into())]),
                    )])),
                )])),
            ),
        ]);
        let rider = rider_from_device_preflight(&preflight, "Rose", &[1, 2]).unwrap();
        assert_eq!(
            rider.request["Rap,ChipID"],
            plist::Value::Integer(8228.into())
        );
        assert_eq!(rider.ticket_key, "Rap,Ticket");
    }

    #[tokio::test]
    async fn batch_failure_retries_individually_and_checks_nonce() {
        let calls = Arc::new(AtomicUsize::new(0));
        let result = prefetch_tss_batch(
            &[rider("Rose", "Rap,Ticket"), rider("SE", "SE2,Ticket")],
            |request| {
                let calls = calls.clone();
                async move {
                    calls.fetch_add(1, Ordering::SeqCst);
                    if request.contains_key("@Rap,Ticket") && request.contains_key("@SE2,Ticket") {
                        return Err(RestoreError::Protocol(
                            "fixture rejects combined request".into(),
                        ));
                    }
                    if request.contains_key("@Rap,Ticket") {
                        Ok(plist::Dictionary::from_iter([(
                            "Rap,Ticket",
                            plist::Value::Data(vec![9]),
                        )]))
                    } else {
                        Err(RestoreError::Protocol("fixture rejects SE".into()))
                    }
                }
            },
        )
        .await
        .unwrap();
        assert_eq!(calls.load(Ordering::SeqCst), 3);
        assert_eq!(result.failed_updaters, ["SE"]);
        assert_eq!(result.tickets["Rose"].for_nonce(&[1, 2, 3]), Some(&[9][..]));
        assert_eq!(result.tickets["Rose"].for_nonce(&[4, 5, 6]), None);
    }

    #[tokio::test]
    async fn missing_ticket_in_combined_reply_retries_that_rider() {
        let calls = Arc::new(AtomicUsize::new(0));
        let result = prefetch_tss_batch(
            &[rider("Rose", "Rap,Ticket"), rider("SE", "SE2,Ticket")],
            |request| {
                let calls = calls.clone();
                async move {
                    calls.fetch_add(1, Ordering::SeqCst);
                    let mut reply = plist::Dictionary::new();
                    if request.contains_key("@Rap,Ticket") {
                        reply.insert("Rap,Ticket".into(), plist::Value::Data(vec![1]));
                    }
                    if request.contains_key("@SE2,Ticket") && !request.contains_key("@Rap,Ticket") {
                        reply.insert("SE2,Ticket".into(), plist::Value::Data(vec![2]));
                    }
                    Ok(reply)
                }
            },
        )
        .await
        .unwrap();
        assert_eq!(calls.load(Ordering::SeqCst), 2);
        assert_eq!(result.tickets.len(), 2);
        assert!(result.failed_updaters.is_empty());
    }

    #[test]
    fn parses_tss_fixture_without_echoing_rejected_response() {
        let mut body = b"STATUS=0&MESSAGE=SUCCESS&REQUEST_STRING=".to_vec();
        plist::to_writer_xml(
            &mut body,
            &plist::Dictionary::from_iter([("Rap,Ticket", plist::Value::Data(vec![1, 2]))]),
        )
        .unwrap();
        assert_eq!(
            parse_tss_response(&body).unwrap()["Rap,Ticket"].as_data(),
            Some(&[1, 2][..])
        );
        assert!(parse_tss_response(b"STATUS=94&MESSAGE=private-detail").is_err());
    }

    #[tokio::test]
    async fn fake_tss_rejects_http_error_and_oversized_body() {
        for (status, body, expected) in [
            ("503 Unavailable", vec![b'x'; 8], "HTTP 503"),
            ("200 OK", vec![b'x'; MAX_TSS_RESPONSE + 1], "exceeds 16 MiB"),
        ] {
            let listener = tokio::net::TcpListener::bind("127.0.0.1:0").await.unwrap();
            let address = listener.local_addr().unwrap();
            let server = tokio::spawn(async move {
                let (mut stream, _) = listener.accept().await.unwrap();
                let mut request = vec![0u8; 4096];
                let _ = stream.read(&mut request).await.unwrap();
                let head = format!(
                    "HTTP/1.1 {status}\r\nContent-Length: {}\r\nConnection: close\r\n\r\n",
                    body.len()
                );
                stream.write_all(head.as_bytes()).await.unwrap();
                if status == "200 OK" {
                    stream.write_all(&body).await.unwrap();
                }
            });
            let client = reqwest::Client::builder()
                .timeout(Duration::from_secs(5))
                .build()
                .unwrap();
            let error = sign_tss_request_with_client(
                &client,
                &format!("http://{address}/TSS/controller?action=2"),
                &rider("Rose", "Rap,Ticket").request,
            )
            .await
            .unwrap_err();
            assert!(error.to_string().contains(expected));
            server.await.unwrap();
        }
    }

    #[tokio::test]
    async fn fake_tss_accepts_xml_plist_post_and_returns_ticket() {
        let listener = tokio::net::TcpListener::bind("127.0.0.1:0").await.unwrap();
        let address = listener.local_addr().unwrap();
        let server = tokio::spawn(async move {
            let (mut stream, _) = listener.accept().await.unwrap();
            let mut request = vec![0u8; 4096];
            let count = stream.read(&mut request).await.unwrap();
            let text = std::str::from_utf8(&request[..count]).unwrap();
            assert!(text.starts_with("POST /TSS/controller?action=2 HTTP/1.1"));
            let mut body = b"STATUS=0&MESSAGE=SUCCESS&REQUEST_STRING=".to_vec();
            plist::to_writer_xml(
                &mut body,
                &plist::Dictionary::from_iter([("Rap,Ticket", plist::Value::Data(vec![9]))]),
            )
            .unwrap();
            let head = format!(
                "HTTP/1.1 200 OK\r\nContent-Length: {}\r\nConnection: close\r\n\r\n",
                body.len()
            );
            stream.write_all(head.as_bytes()).await.unwrap();
            stream.write_all(&body).await.unwrap();
        });
        let client = reqwest::Client::builder()
            .timeout(Duration::from_secs(5))
            .build()
            .unwrap();
        let response = sign_tss_request_with_client(
            &client,
            &format!("http://{address}/TSS/controller?action=2"),
            &rider("Rose", "Rap,Ticket").request,
        )
        .await
        .unwrap();
        assert_eq!(response["Rap,Ticket"].as_data(), Some(&[9][..]));
        server.await.unwrap();
    }

    #[tokio::test]
    async fn tss_request_budget_rejects_before_network() {
        let mut request = rider("Rose", "Rap,Ticket").request;
        request.insert(
            "Oversized".into(),
            plist::Value::Data(vec![0; MAX_TSS_REQUEST]),
        );
        let client = reqwest::Client::new();
        let error = sign_tss_request_with_client(&client, "http://127.0.0.1:1", &request)
            .await
            .unwrap_err();
        assert!(error.to_string().contains("exceeds 4 MiB"));
    }
}
